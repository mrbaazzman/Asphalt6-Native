#!/usr/bin/env python3
"""Emit chunked C translation units, dispatch table, and link M2 test or runtime."""
import argparse
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "recomp"))
sys.path.insert(0, str(ROOT / "tools"))

from emit_c import Emitter, PRELUDE, PLT_START, PLT_END  # noqa: E402
from pcode import parse  # noqa: E402
import hostinfo  # noqa: E402
import prereq  # noqa: E402
from pyrun import NO_WINDOW  # noqa: E402

SO = ROOT / "analysis/apk_extract/lib/armeabi-v7a/libasphalt6.so"
PCODE_ALL = ROOT / "analysis/reports/pcode_all.tsv"
PCODE_EXTRA = ROOT / "analysis/reports/pcode_extra.tsv"
OUT_DIR = ROOT / "build/link"
STACK_TOP = 0x01800000


def write_if_changed(path: Path, text: str) -> bool:
    if path.exists():
        try:
            if path.read_text(encoding="utf-8") == text:
                return False
        except OSError:
            pass
    path.write_text(text, encoding="utf-8")
    return True


def compiler() -> str:
    if os.environ.get("CC"):
        return os.environ["CC"]
    found = shutil.which("gcc")
    if found:
        return found
    fetched = prereq.find_fetched("mingw")
    if fetched:
        for name in ("gcc.exe", "gcc"):
            candidate = fetched / "bin" / name
            if candidate.exists():
                return str(candidate)
    return "gcc"


def load_functions(tsv_paths):
    by_entry = {}
    image_base = 0x10000
    for p in tsv_paths:
        if not p.exists() or p.stat().st_size == 0:
            continue
        header, funcs = parse(p)
        if header and len(header) > 1:
            image_base = int(header[1], 16)
        for f in funcs:
            if f.external or not f.insns:
                continue
            if f.entry not in by_entry:
                by_entry[f.entry] = f
    funcs = sorted(by_entry.values(), key=lambda f: f.entry)
    return image_base, funcs


def make_guest_image() -> None:
    guest_bin = ROOT / "build/guest.bin"
    if guest_bin.exists() and guest_bin.stat().st_mtime >= SO.stat().st_mtime:
        return
    subprocess.run([sys.executable, str(ROOT / "tools/patch_guest.py")],
                   cwd=ROOT, check=True)


def emit_chunks(funcs, image_base: int, chunk_size: int, out_dir: Path):
    chunks = []
    changed = 0
    for idx in range(0, len(funcs), chunk_size):
        batch = funcs[idx:idx + chunk_size]
        lines = [
            "/* generated by recomp/link_all.py; do not edit */",
            '#include "cpu.h"',
            '#include "mem.h"',
            "#include <math.h>",
            "",
            PRELUDE.rstrip(),
            "",
            "void call_target(Cpu *c, uint8_t *mem, uint32_t target);",
            "void call_indirect(Cpu *c, uint8_t *mem, uint32_t target);",
            "void call_import(Cpu *c, uint8_t *mem, uint32_t plt);",
            "",
        ]
        for f in batch:
            lines.append(Emitter(f, image_base).emit_body())
        path = out_dir / f"chunk_{idx // chunk_size:03d}.c"
        if write_if_changed(path, "\n".join(lines) + "\n"):
            changed += 1
        chunks.append(path)
    return chunks, changed


def emit_table(funcs, out_dir: Path):
    lines = [
        "/* generated by recomp/link_all.py; do not edit */",
        '#include "cpu.h"',
        "",
        "typedef void (*FnPtr)(Cpu *c, uint8_t *mem);",
        "typedef struct { uint32_t addr; FnPtr fn; } FnEntry;",
        "",
    ]
    for f in funcs:
        lines.append(f"void fn_{f.entry:06x}(Cpu *c, uint8_t *mem);")
    lines.append("")
    lines.append(f"const uint32_t k_plt_start = 0x{PLT_START:06x}u;")
    lines.append(f"const uint32_t k_plt_end = 0x{PLT_END:06x}u;")
    lines.append(f"const uint32_t k_func_count = {len(funcs)}u;")
    lines.append("")
    lines.append("const FnEntry k_funcs[] = {")
    for f in funcs:
        lines.append(f"    {{ 0x{f.entry:06x}u, fn_{f.entry:06x} }},")
    lines.append("};")
    lines.append("")
    path = out_dir / "table.c"
    changed = 1 if write_if_changed(path, "\n".join(lines)) else 0
    return path, changed


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv", nargs="?", default=str(PCODE_ALL))
    ap.add_argument("--extra", default=str(PCODE_EXTRA))
    ap.add_argument("--chunk", type=int, default=250)
    ap.add_argument("--jobs", type=int, default=0)
    ap.add_argument("--emit-only", action="store_true")
    ap.add_argument("--boot", action="store_true",
                    help="Compile and run M2 constructor/boot probe")
    ap.add_argument("--test-entry", help="Run a single guest function address (hex)")
    args = ap.parse_args()

    if not args.jobs:
        args.jobs = hostinfo.jobs()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    tsvs = [Path(args.tsv)]
    if args.extra:
        tsvs.append(Path(args.extra))

    image_base, funcs = load_functions(tsvs)
    chunks, ch1 = emit_chunks(funcs, image_base, args.chunk, OUT_DIR)
    table_path, ch2 = emit_table(funcs, OUT_DIR)
    changed = ch1 + ch2

    # Remove stale chunks if chunk count shrank
    keep = set(chunks)
    for old in OUT_DIR.glob("chunk_*.c"):
        if old not in keep:
            old.unlink()
            old_o = old.with_suffix(".o")
            if old_o.exists():
                old_o.unlink()
            changed += 1

    make_guest_image()
    if args.emit_only:
        print(f"emitted {len(chunks)} chunks and {len(funcs)} functions "
              f"({changed} file(s) changed, no compile)")
        return 0

    from elf_image import Image
    img = Image(SO)
    img.apply_relocations()
    ctors = img.init_array()
    ctor_lines = ",\n    ".join(f"0x{a:08x}u" for a in ctors)

    common = f"""#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <setjmp.h>
#include "cpu.h"
#include "mem.h"

void call_target(Cpu *c, uint8_t *mem, uint32_t target);
void guest_init_data(uint8_t *mem, uint32_t mem_size);
void java_bridge_init(uint8_t *mem, uint32_t mem_size);

uint32_t guest_mem_size = 0x20000000u;
static uint8_t *g_mem = NULL;
static jmp_buf g_fault_jmp;
static int g_fault_armed = 0;
static uint32_t g_fault_addr = 0;
static int g_fault_kind = 0;

void guest_fault(uint32_t addr, int write) {{
    g_fault_addr = addr;
    g_fault_kind = write;
    if (g_fault_armed) longjmp(g_fault_jmp, 1);
    fprintf(stderr, "FATAL guest_fault addr=0x%08x kind=%d\\n", addr, write);
    exit(2);
}}

int call_override(Cpu *c, uint8_t *mem, uint32_t target) {{
    (void)c; (void)mem; (void)target;
    return 0;
}}

static const uint32_t k_ctors[] = {{
    {ctor_lines}
}};

int main(void) {{
    g_mem = (uint8_t *)calloc(1, guest_mem_size);
    if (!g_mem) {{ fprintf(stderr, "OOM\\n"); return 1; }}
    FILE *f = fopen("build/guest.bin", "rb");
    if (!f) {{ perror("build/guest.bin"); return 1; }}
    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    fseek(f, 0, SEEK_SET);
    if (sz <= 0 || (uint32_t)sz > guest_mem_size ||
        fread(g_mem, 1, (size_t)sz, f) != (size_t)sz) {{
        fprintf(stderr, "failed to load guest.bin\\n");
        return 1;
    }}
    fclose(f);
    guest_init_data(g_mem, guest_mem_size);
    java_bridge_init(g_mem, guest_mem_size);
"""

    if args.test_entry:
        test_entry = int(args.test_entry, 16) & ~1
        main_c = common + f"""
    Cpu c;
    memset(&c, 0, sizeof c);
    c.lr = 0xDEADBEE0u;
    c.sp = {STACK_TOP:#x}u;
    call_target(&c, g_mem, 0x{test_entry:06x}u);
    printf("fn_{test_entry:06x}: r0=%u (0x%08x)\\n", c.r0, c.r0);
    return 0;
}}
"""
        main_path = OUT_DIR / "main_test.c"
        exe = ROOT / "build/asphalt6_recomp_test.exe"
    else:
        main_c = common + f"""
    size_t n = sizeof(k_ctors) / sizeof(k_ctors[0]);
    size_t ok = 0;
    for (size_t i = 0; i < n; i++) {{
        Cpu c;
        memset(&c, 0, sizeof c);
        c.lr = 0xDEADBEE0u;
        c.sp = {STACK_TOP:#x}u;
        g_fault_armed = 1;
        if (setjmp(g_fault_jmp) == 0) {{
            call_target(&c, g_mem, k_ctors[i]);
            ok++;
        }} else {{
            g_fault_armed = 0;
            fprintf(stderr, "CTOR[%zu] 0x%08x FAULTED at 0x%08x kind=%d\\n",
                    i, k_ctors[i], g_fault_addr, g_fault_kind);
            return 1;
        }}
        g_fault_armed = 0;
    }}
    printf("M2 BOOT OK: %zu/%zu .init_array constructors ran with 0 faults\\n", ok, n);
    return 0;
}}
"""
        main_path = OUT_DIR / "main_boot.c"
        exe = ROOT / "build/asphalt6_boot_test.exe"

    write_if_changed(main_path, main_c)
    cc = compiler()

    def compile_one(path: Path):
        obj = path.with_suffix(".o")
        if obj.exists() and obj.stat().st_mtime >= path.stat().st_mtime:
            return path, 0, ""
        opt = "-O0" if path.name == "table.c" else "-O1"
        proc = subprocess.run(
            [cc, "-std=c11", opt, "-Wall", "-Wextra",
             "-I", str(ROOT / "runtime"), "-c", str(path), "-o", str(obj)],
            capture_output=True, text=True, creationflags=NO_WINDOW)
        return path, proc.returncode, proc.stderr

    sources = chunks + [table_path, main_path]
    failures = []
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        for path, rc, err in pool.map(compile_one, sources):
            if rc != 0:
                failures.append((path.name, rc, err))
    if failures:
        for name, rc, err in failures[:5]:
            print(f"COMPILE FAIL {name} ({rc})\n{err[:2000]}")
        return 1

    runtime_objs = []
    for name in ("dispatch.c", "imports.c", "java_bridge.c", "guest_data.c", "vfs.c", "thread_win32.c"):
        src = ROOT / "runtime" / name
        if not src.exists():
            print(f"missing runtime source for link test: {src}")
            return 1
        obj = OUT_DIR / (src.stem + ".o")
        proc = subprocess.run(
            [cc, "-std=c11", "-O1", "-Wall", "-Wextra", "-DM2_BOOT_STUB",
             "-I", str(ROOT / "runtime"), "-c", str(src), "-o", str(obj)],
            capture_output=True, text=True, creationflags=NO_WINDOW)
        if proc.returncode != 0:
            print(f"RUNTIME COMPILE FAIL {name}\n{proc.stderr[:2000]}")
            return 1
        runtime_objs.append(str(obj))

    objs = [str(p.with_suffix(".o")) for p in sources] + runtime_objs
    link = subprocess.run([cc, *objs, "-o", str(exe), "-lm", "-lwinmm"],
                          capture_output=True, text=True, creationflags=NO_WINDOW)
    if link.returncode != 0:
        print("LINK FAILED\n" + link.stderr[:4000])
        return 1
    print(f"linked {exe}")

    run = subprocess.run([str(exe)], cwd=ROOT, capture_output=True, text=True)
    if run.stdout:
        print(run.stdout.strip())
    if run.stderr:
        print(run.stderr.strip(), file=sys.stderr)
    return run.returncode


if __name__ == "__main__":
    raise SystemExit(main())
